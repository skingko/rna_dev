#!/usr/bin/env node
// Historical protocol-only fixture suite. Actual semantic validation lives in
// test-openviking-semantic.mjs. Never select the fixture implicitly.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { Store } from '../prototypes/control-center/store.mjs';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
if (!process.argv.includes('--fixture')) throw new Error('Protocol fixtures require explicit --fixture; use the real semantic integration suite for production validation.');
const config = JSON.parse(readFileSync(join(root, 'deploy/openviking/.runtime/rna-client.json'), 'utf8'));
const endpoint = 'http://127.0.0.1:1933';
const folder = mkdtempSync(join(tmpdir(), 'rna-openviking-live-'));
const store = new Store(join(folder, 'state.json'));
store.configurationService.update({ memory: { backend: 'openviking', endpoint, apiKey: config.api_key } });
const checks = [];
const check = (name, fn) => Promise.resolve().then(fn).then(() => { checks.push({ name, ok: true }); console.log(`PASS ${name}`); });
const nap = ms => new Promise(resolve => setTimeout(resolve, ms));
let project, uri, binding, commit;
const report = { service: 'official OpenViking Docker', image: 'ghcr.io/volcengine/openviking:v0.4.21.1@sha256:13a78525aa255f0cdb026bfdc1ab8c3a9b2baa49148aa10df061e6c2b689c15f',
  modelBackend: 'deterministic local protocol fixture; no semantic quality claim', startedAt: new Date().toISOString(), checks };
try {
  ({ project } = store.createProject({ name: 'Rna OpenViking integration test', description: 'Disposable live protocol test, no user conversation.' }));
  report.namespace = `viking://resources/projects/${project.id}`;
  await check('health and authenticated initialization status', async () => assert.equal((await store.memoryService.health(project.id)).initialized, true));
  await check('authentication rejects requests without a key', async () => assert.equal((await fetch(`${endpoint}/api/v1/system/status`)).status, 401));
  await check('initialize an isolated project namespace', async () => assert.equal((await store.memoryService.initialize(project.id)).initialized, true));
  await check('initialize is idempotent', async () => assert.equal((await store.memoryService.initialize(project.id)).existed, true));
  await check('write a real persisted project resource', async () => {
    const written = await store.memoryService.write(project.id, null, { title: 'RNA_MEMORY_TEST', content: 'RNA_MEMORY_TEST cache budgeting and checkpoint recovery. Persist this integration-only record.' });
    uri = written.uri; assert.equal(written.accepted, true);
  });
  await check('read returns the original file content', async () => assert.match((await store.memoryService.read(project.id, { uri, level: 'L2' })).content, /Persist this integration-only record/));
  await check('browse returns the scoped resource', async () => assert.ok((await store.memoryService.browse(project.id)).entries.some(row => row.uri === uri)));
  await check('adapter rejects cross-project reads before HTTP', async () => assert.rejects(store.memoryService.read(project.id, { uri: 'viking://resources/projects/foreign/private.md', level: 'L2' }), /当前项目/));
  await check('actual vector indexing and scoped find', async () => {
    let found;
    for (let attempt = 0; attempt < 60; attempt++) {
      found = await store.memoryService.search(project.id, { query: 'RNA_MEMORY_TEST cache budgeting and checkpoint recovery', level: 'L2' });
      if (found.entries.some(row => row.uri === uri)) break;
      await nap(1000);
    }
    assert.ok(found.entries.some(row => row.uri === uri), 'resource was not indexed within 60 seconds');
    assert.ok(found.entries.every(row => row.uri.startsWith(`${report.namespace}/`) || row.uri === report.namespace));
  });
  await check('L0 abstract and L1 overview generated by official service', async () => {
    const abstract = await store.memoryService.read(project.id, { uri: report.namespace, level: 'L0' });
    const overview = await store.memoryService.read(project.id, { uri: report.namespace, level: 'L1' });
    assert.ok(abstract.content.length); assert.ok(overview.content.length);
  });
  await check('create and bind a real remote session', async () => { binding = await store.memoryService.createSession(project.id); assert.ok(binding.sessionId); });
  await check('write a batch to the remote session', async () => {
    const messages = [{ role: 'user', content: 'For this integration test, preserve the checkpoint before retry.' }, { role: 'assistant', content: 'The synthetic test record requests checkpoint preservation.' }];
    assert.equal((await store.memoryService.sessionMessages(project.id, binding.sessionId, { messages })).accepted, true);
  });
  await check('commit returns a real archive and tracked background task', async () => {
    commit = await store.memoryService.sessionCommit(project.id, binding.sessionId);
    assert.ok(commit.result.task_id); report.sessionId = binding.sessionId; report.taskId = commit.result.task_id;
  });
  await check('background commit reaches successful terminal state', async () => {
    let result;
    for (let attempt = 0; attempt < 90; attempt++) {
      result = (await store.memoryService.sessionTask(project.id, binding.sessionId, commit.result.task_id)).result;
      if (['completed', 'failed', 'cancelled'].includes(result.status)) break;
      await nap(1000);
    }
    report.commitStatus = result?.status; assert.equal(result?.status, 'completed');
  });
  if (process.argv.includes('--restart')) {
    await check('persisted resource survives official container restart', async () => {
      execFileSync('python3', [join(root, 'scripts/openviking-local.py'), 'restart', '--fixture'], { stdio: 'pipe' });
      for (let attempt = 0; attempt < 60; attempt++) {
        try { await store.memoryService.health(project.id); break; } catch { await nap(1000); }
      }
      assert.match((await store.memoryService.read(project.id, { uri, level: 'L2' })).content, /Persist this integration-only record/);
    });
  }
  report.ok = true;
} catch (error) {
  report.ok = false; report.error = error.message; console.error(`FAIL ${error.message}`); process.exitCode = 1;
} finally {
  report.finishedAt = new Date().toISOString();
  writeFileSync(join(root, 'deploy/openviking/integration-report.json'), JSON.stringify(report, null, 2));
  rmSync(folder, { recursive: true, force: true });
  console.log(JSON.stringify({ ok: report.ok, passed: checks.length, modelBackend: report.modelBackend }));
}
